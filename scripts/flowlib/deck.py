from flowlib.parsers import parse_subckt_ports

PORT_ORDER = ["in", "out", "vdd", "vss"]


def make_deck(dut_netlist, tb, model_lib, corner, design):
    """Top-level ngspice deck: models, the DUT netlist, then the testbench.

    Refuses a DUT whose subcircuit ports are not in the canonical order,
    because the testbench connects to them by position.
    """
    with open(dut_netlist) as f:
        ports = parse_subckt_ports(f.read(), design)
    if ports != PORT_ORDER:
        raise ValueError(
            f"{dut_netlist}: .subckt {design} ports are {ports}, expected {PORT_ORDER}"
        )
    return (
        f"* generated by flowlib.deck for {design}\n"
        f'.lib "{model_lib}" {corner}\n'
        f'.include "{dut_netlist}"\n'
        f'.include "{tb}"\n'
        ".end\n"
    )
