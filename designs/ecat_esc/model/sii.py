"""The ESC's SII contents, the single source for the reference model and for rtl/sii_rom.v
(scripts/gen_sii_rom.py writes that file from render_rom()).

The identity is a placeholder: a real vendor ID comes from the EtherCAT Technology Group, and
the ROM freezes whatever is here at tapeout. The device has no mailbox, and takes its process
data layout from the SyncM and PDO categories: 8 bytes out at 0x1000 through SM2, 8 bytes in at
0x1080 through SM3."""
import struct

WORDS = 128                     # 256 bytes, a 2 Kbit EEPROM
VENDOR, PRODUCT, REVISION, SERIAL = 0, 1, 1, 0
NAME = "OS-ESC"
OUT_ADDR, IN_ADDR, PD_BYTES = 0x1000, 0x1080, 8

PDI_CONTROL = 0x0100            # 0x0141 bit 0: device emulation, AL status follows AL control
SIZE_WORD, VERSION_WORD = 1, 1  # size in Kbit, minus 1


def crc8(data):
    """The SII config-area checksum: polynomial 0x07, initial value 0xFF."""
    crc = 0xFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = ((crc << 1) ^ 0x07) & 0xFF if crc & 0x80 else (crc << 1) & 0xFF
    return crc


def _category(kind, body):
    if len(body) % 2:
        body += b"\x00"
    return struct.pack("<HH", kind, len(body) // 2) + body


def _pdo(index, sm, entry_index):
    return (struct.pack("<HBBBBH", index, 1, sm, 0, 0, 0)
            + struct.pack("<HBBBBH", entry_index, 1, 0, 0, 8 * PD_BYTES, 0))


def _sm(start, length, control, kind):
    return struct.pack("<HHBBBB", start, length, control, 0, 1, kind)


def image():
    """256 bytes, padded with 0xFF as a blank EEPROM reads."""
    config = struct.pack("<7H", PDI_CONTROL, 0, 0, 0, 0, 0, 0)
    config += bytes([crc8(config), 0])
    head = bytearray(config + struct.pack("<4I", VENDOR, PRODUCT, REVISION, SERIAL))
    head.extend(bytes(2 * 0x40 - len(head)))
    struct.pack_into("<HH", head, 2 * 0x3E, SIZE_WORD, VERSION_WORD)

    name = NAME.encode()
    body = bytes(head)
    body += _category(10, bytes([1, len(name)]) + name)
    body += _category(30, bytes([0, 0, 0, 1]) + bytes(12))
    body += _category(40, bytes([1, 2, 0xFF, 0]))
    body += _category(41, bytes(16) + _sm(OUT_ADDR, PD_BYTES, 0x64, 3) + _sm(IN_ADDR, PD_BYTES, 0x20, 4))
    body += _category(50, _pdo(0x1A00, 3, 0x6000))
    body += _category(51, _pdo(0x1600, 2, 0x7000))
    body += b"\xff\xff"
    if len(body) > 2 * WORDS:
        raise ValueError(f"SII image is {len(body)} bytes, the table holds {2 * WORDS}")
    return body.ljust(2 * WORDS, b"\xff")


def read32(word_addr):
    """What the SII data register holds for this word address: a word at or past WORDS
    reads 0xFFFF."""
    data = image()
    out = b""
    for a in (word_addr, word_addr + 1):
        out += data[2 * a:2 * a + 2] if a < WORDS else b"\xff\xff"
    return out


def render_rom():
    """The text of rtl/sii_rom.v."""
    data = image()
    rows = [f"            7'd{w}: data = 16'h{data[2 * w] | data[2 * w + 1] << 8:04x};"
            for w in range(WORDS)]
    return "\n".join([
        "// Generated by scripts/gen_sii_rom.py from designs/ecat_esc/model/sii.py. Do not edit:",
        "// model/test_sii.py fails if this file differs from what the generator writes.",
        "// The SII contents as 16-bit words, addressed by word.",
        "module sii_rom (",
        "    input      [6:0]  addr,",
        "    output reg [15:0] data",
        ");",
        "    always @* begin",
        "        case (addr)",
        *rows,
        "            default: data = 16'hffff;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ])
